// サインアップ時のメールアドレス確認・メールアドレス変更の承認・パスワードリセットの通知メール件名・本文テンプレート
// (docs/architecture.md 第11節)。account-deletion-emails.tsと同程度のトーン(丁寧・簡潔な
// 日本語のプレーンテキスト)に揃える

// メールアドレス確認メール。Better Authのemail-verificationプラグインの
// sendVerificationEmailコールバックから呼び出す。urlはトークン付きの確認リンクで、
// クリックすると/api/auth/verify-emailで検証された後、callbackURLへリダイレクトされる。
//
// このコールバックは、新規登録時の確認メールと、メールアドレス変更時の新しいアドレスへの確認メールの
// 両方から呼ばれ、どちらの場合か(コールバックの引数には)区別が付かない。そのため、どちらの場合に
// 届いても不自然にならない文面にしている(「ご登録ありがとうございます」のような新規登録専用の挨拶は避ける)
export function buildEmailVerificationEmail(url: string): { subject: string; text: string } {
  return {
    subject: '【kyurl.link】メールアドレスの確認をお願いします',
    text: `kyurl.linkで、このメールアドレスの確認をお願いします。
(新規登録、またはメールアドレスの変更のお手続きで、このアドレスが指定されました。)

以下のリンクをクリックして、メールアドレスの確認を完了してください。

${url}

リンクの有効期限は1時間です。期限が切れた場合は、ログイン後に確認メールを再送してください。
メールアドレスの変更の場合は、このリンクを開いた時点で、アカウントのメールアドレスがこのアドレスに変わります。

このメールに心当たりがない場合は、破棄していただいて問題ありません。リンクを開かない限り、登録も変更も完了しません。

ご不明点は info@kyurl.link までご連絡ください。`,
  }
}

// メールアドレス変更の承認メール(今のアドレス宛て)。Better Authのuser.changeEmail.
// sendChangeEmailConfirmationコールバックから呼び出す。確認済みのユーザーがメールアドレスの変更を
// 申請すると、まず今のアドレスにこのメールが送られ、リンクを開くと新しいアドレスへ確認メール
// (buildEmailVerificationEmail)が送られる。ログイン状態を盗まれた場合にアドレスを乗っ取られないよう、
// 今のアドレスの持ち主が承認しない限り変更を進めない二段階の確認にしている。
// 心当たりがない場合の案内として、パスワードの変更を勧める(第三者がログイン状態を持っている恐れがあるため)
export function buildChangeEmailConfirmationEmail(newEmail: string, url: string): { subject: string; text: string } {
  return {
    subject: '【kyurl.link】メールアドレス変更の承認をお願いします',
    text: `kyurl.linkのアカウントで、メールアドレスの変更が申請されました。

変更後のメールアドレス:${newEmail}

申請された方がご本人の場合は、以下のリンクをクリックして、変更を承認してください。
承認すると、変更後のメールアドレスに確認メールをお送りします。そのメールのリンクを開いた時点で、メールアドレスが変更されます。

${url}

リンクの有効期限は1時間です。リンクを開くまでは、メールアドレスは変更されません。

このメールに心当たりがない場合は、リンクを開かずに破棄してください。第三者がアカウントにログインしている恐れがあるため、念のため、ログイン後にパスワードを変更してください。

ご不明点は info@kyurl.link までご連絡ください。`,
  }
}

// パスワードリセットメール。Better Authのemail-and-passwordプラグインの
// sendResetPasswordコールバックから呼び出す。urlはトークン付きのリセットリンクで、
// クリックするとフロントエンドのパスワード再設定画面(/reset-password/confirm)へ
// トークン付きで遷移する
export function buildPasswordResetEmail(url: string): { subject: string; text: string } {
  return {
    subject: '【kyurl.link】パスワード再設定のご案内',
    text: `パスワード再設定のお申し込みを受け付けました。

以下のリンクから新しいパスワードを設定してください。

${url}

リンクの有効期限は1時間です。一度使うと無効になります。

このメールに心当たりがない場合は、第三者が誤ってメールアドレスを入力した可能性があります。
その場合は本メールを破棄していただいて問題ありません(このリンクからパスワードが変更されることはありません)。

ご不明点は info@kyurl.link までご連絡ください。`,
  }
}
